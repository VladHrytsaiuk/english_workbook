// Builds src/shared/irregularData.ts from the workbook note (tables of groups 1–6 + variants). Run: node scripts/gen-irregular.mjs <note.md>
import { readFileSync, writeFileSync } from 'node:fs'
const src = readFileSync(process.argv[2], 'utf8').split('\n')
const top = new Map()
let section = ''
const out = []
for (const line of src) {
  const h = line.match(/^(#{2,3}) (.*)/)
  if (h) { section = h[2]; continue }
  const m = line.match(/^\|\s*(\d+)?\s*\|?\s*\*\*([^*|]+)\*\*\s*\|\s*([^|]+)\|\s*([^|]+)\|\s*([^|]+)\|?$/) // top-60 rows: # | V1 | V2 | V3 | uk
  if (/^(1–20|21–40|41–60)/.test(section) && m && m[1]) { top.set(m[2].trim(), Number(m[1])); continue }
}
const groupOf = (s) => { const n = s.match(/^([1-6])\. /); if (n) return Number(n[1]); if (/^Два варіанти/.test(s)) return 7; return 0 }
section = ''
for (const line of src) {
  const h = line.match(/^## (.*)/)
  if (h) { section = h[1]; continue }
  const g = groupOf(section)
  if (!g) continue
  const m = line.match(/^\|\s*\*\*([^*|]+)\*\*\s*\|\s*([^|]+)\|\s*([^|]+)\|\s*([^|]+)\|$/)
  if (!m) continue
  out.push({ v1: m[1].trim(), v2: m[2].trim(), v3: m[3].trim(), uk: m[4].trim(), group: g, ...(top.has(m[1].trim()) ? { top: top.get(m[1].trim()) } : {}) })
}
const seen = new Set()
for (const v of out) { v.id = seen.has(v.v1) ? `${v.v1}-${v.group}` : v.v1; seen.add(v.v1) }
const body = out.map((v) => '  ' + JSON.stringify(v).replace(/"(\w+)":/g, '$1:').replace(/'/g, "\\'").replace(/"/g, "'")).join(',\n')
writeFileSync('src/shared/irregularData.ts', `// Generated by scripts/gen-irregular.mjs from notes/grammar/06-irregular-verbs.md — edit the script's source note, not this file.\nimport type { IrregularVerb } from './types'\n\nexport const IRREGULAR_VERBS: IrregularVerb[] = [\n${body}\n]\n`)
console.log(out.length, 'verbs;', [...new Set(out.map((v) => v.group))].map((g) => g + ':' + out.filter((v) => v.group === g).length).join(' '), 'top:', out.filter((v) => v.top).length)
